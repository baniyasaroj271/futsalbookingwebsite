def seed_venues():
    existing_slugs = {slug for (slug,) in Venue.query.with_entities(Venue.slug)}
    for venue_data in VENUES:
        if venue_data["slug"] in existing_slugs:
            continue
        db.session.add(Venue(**venue_data))
        try:
            db.session.commit()
        except IntegrityError:
            db.session.rollback()
            if not Venue.query.filter_by(slug=venue_data["slug"]).first():
                raise
        else:
            existing_slugs.add(venue_data["slug"])


